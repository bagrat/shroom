#!/usr/bin/env python3
"""Write phase 1's change report (REPORT.md here) from what assemble.py did: every place
spec/machine.json differs from the old spec, each with its citation, the ones that are
Bagrat's to ratify first. Run after assemble.py.
"""
import collections
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.dont_write_bytecode = True  # no __pycache__ beside the tools
sys.path.insert(0, str(HERE))
import overlay  # noqa: E402
from ids import RENAME  # noqa: E402

M = json.loads((ROOT / "spec/machine.json").read_text())
N = json.loads((HERE / "assemble-notes.json").read_text())
MOVES = json.loads((HERE / "moves.json").read_text())
S = M["states"]
GH = "https://github.com/bagrat/shroom/blob/main/"
DEV = GH + "docs/DECISIONS.md#deviations-from-the-spec"

out = []
w = out.append


def cite(c):
    if c.startswith("#"):
        return f"[DEVIATIONS {c}]({DEV})"
    return c


def cites(cs):
    return ", ".join(cite(c) for c in cs)


old_fixture = sum(len(json.loads((ROOT / f"history/spec/r{i}.json").read_text())["states"]) for i in range(1, 7))
old_map = json.loads((ROOT / "history/spec/map.json").read_text())
covered = N["covered"]
by_rule = sum(v for k, v in covered.items() if k.startswith("rule:"))
by_edge = covered.get("edge", 0) + covered.get("edge (a face of its state)", 0)
new_edges = [e for e in M["edges"] if "core-run" in e["source"] and not ({"map", "fixture"} & set(e["source"]))]
src = collections.Counter()
for e in M["edges"]:
    s = set(e["source"])
    src["drawn by the map or the fixtures" if s & {"map", "fixture"} else ("named by the core's arms" if "core-arm" in s else "made by the core in a run")] += 1

w("# Phase 1 — what changed on the way into `spec/machine.json`")
w("")
w("*Machine-json phase 1 ([B133](../../../docs/DECISIONS.md) *(the machine becomes one JSON)*, plan: "
  "[`machine-json.md`](../machine-json.md)). Generated by `report.py` after `assemble.py`; regenerate, don't edit.*")
w("")
w("`spec/machine.json` is the old spec's six fixtures, the map and `meta.json` merged under one id per state, "
  "with the implementation laid over them wherever the two differ. "
  "Nothing reads it yet: phase 2 points the tests at it. "
  "This report lists every place it differs from the old spec. You never need to open the JSON.")
w("")
w("## In numbers")
w("")
w("| | Old spec | `machine.json` |")
w("|---|---|---|")
w(f"| States | {old_fixture} in the fixtures (one twice), {len(old_map['states'])} on the map, the code showing 111 | {len(S)} |")
w(f"| Ids per state | up to four (fixture, map, code, alias tables) | one |")
w(f"| Edges | {len(old_map['edges'])} on the map, 255 fixture transitions, 82 named by the core | {len(M['edges'])} |")
w(f"| Rules | prose, and two Rust functions in the enumeration test | {len(M['rules'])} |")
w(f"| Said-lines | {sum(len(s['said_lines']) for i in range(1, 7) for s in json.loads((ROOT / f'history/spec/r{i}.json').read_text())['states'])} | {sum(len(s['said']) for s in S.values())}, each with an id |")
w("")
w(f"Every move the core made across all 248 of its tests (recorded by `record-moves.patch`, {len(MOVES)} distinct moves) "
  f"is now an edge or falls under a rule: {by_edge} on an edge, {by_rule} under a rule, and {covered.get('new edge', 0)} "
  f"that neither covered became {len(new_edges)} new edges ({sum(e['status'] == 'ratified' for e in new_edges)} ratified in B134, the rest `provisional`). "
  f"The edges: {', '.join(f'{v} {k}' for k, v in src.items())}.")
w("")

# ── Bagrat's ────────────────────────────────────────────────────────────────────
w("## Still yours to ratify")
w("")
w("1. **The landing's demo** — " + cite("#29") + ". landing → live (“watch the demo”) is `provisional` until "
  "your demo recording exists; the block waits, hidden. Release-blocking, and only you can record it.")
w("")
w("## Ratified by you on 2026-10-14 (B134)")
w("")
w("Where adopting the implementation changed a ratified line or move. You said “ratify 1, 2, 3, 5, 6” after the "
  "walkthrough; each is now `ratified` in the JSON and cites B134.")
w("")
w("1. **Restart asks first** — " + cite("#44") + ". A new state, `restart-confirm`: "
  "“Start over?” · “This replaces the 4:32 you've recorded so far.” · Back · [ Restart ]. "
  "The drawn edge paused → countdown (“Restart — count already running”, N24/N39) is gone; Restart now goes "
  "paused → restart-confirm → countdown, and Back returns to paused.")
w("2. **The born invite's link is masked** — " + cite("#22") + ". `invite-born` (and `add-another-mac`): the pill shows "
  "“v.myshroom.workers.dev/join/” and the code stays hidden; [ Copy link ] is the only way to it, where N28 drew the full link.")
w("3. **“For macOS 14 or newer, Apple silicon.”** — B7, B44, the copy table. `landing` and `join-landing`: the fill "
  "drops “and Intel”, since everything built is arm64-only.")
ruled = [e for e in M["edges"] if (e["from"], e["to"]) in set(overlay.RULED_EDGES)]
w(f"4. **{len(ruled)} moves the code makes between ratified states that no drawing showed**, as a batch:")
w("")
w("   | From | To | On | Cites |")
w("   |---|---|---|---|")
for e in ruled:
    w(f"   | `{e['from']}` | `{e['to']}` | {e['label']} | {cites(e['cites'])} |")
w("")
built_rules = [r for r in M["rules"] if "B134" in r["cites"]]
w(f"5. **{len(built_rules)} rules written from the build**, where the old spec had prose or nothing:")
w("")
for r in built_rules:
    w(f"   - **{r['label']}** (`{r['id']}`, {cites(r['cites'])}) — {r['says']}")
w("")

w("## Already yours, now in the JSON")
w("")
w("Changes to ratified lines you had already ratified, in the asking or the drawing, before this report. Recorded here, nothing to do.")
w("")
for sid, old, new, cs, why, status in N["copy-changed"]:
    if "ratified by Bagrat" in why and "B134" not in why:
        w(f"- `{sid}`: “{old}” → “{new}” — {cites(cs)}, {why}.")
for sid, text, cs, why in N["copy-added"]:
    w(f"- `{sid}` gains “{text}” — {cites(cs)}, {why}.")
for sid, old, cs, why, status in N["copy-dropped"]:
    w(f"- `{sid}` drops “{old}” — {cites(cs)}, {why}.")
for line in N["retired"]:
    w(f"- Retired: {line.replace('(DEVIATIONS #50, B132)', '(' + cite('#50') + ', B132)')}.")
w("- “" + "Fully live ✓” edge: owner-page → fully-live stays (the page still reaches it), now `provisional` with " + cite("#46") + " — its line is gone from the page.")
w("")

# ── not product changes ─────────────────────────────────────────────────────────
w("## Not a product change")
w("")
w("### One id per state")
w("")
w("Every state now has one kebab-case id (the spec's own notation), used by the code, the tests and the canvas. "
  "Phase 2 renames the code's ids and deletes the four alias tables. Where the map had a kebab name, it won.")
w("")
w("| Was | Now |")
w("|---|---|")
for old, new in RENAME.items():
    w(f"| {old} | `{new}` |")
w("")
w("The map's other names: `flaunch` → `first-launch`, `idle` → `idle-unprovisioned`, `degraded` → `space-degraded`, "
  "`exit-confirm` → `disconnect-confirm`, and `auto-pause` became a group (`mac-away`, `mic-lost`, `camera-lost`, "
  "`mic-permission-lost`). The map's 13 ports are gone: each edge now goes to the state on the far side.")
w("")
w("### States")
w("")
for line in N["code-states"]:
    sid = line.split("`")[1]
    w(f"- **Only the code had it:** {line.replace('cites ', 'cites ').replace('#25', cite('#25')).replace('#44', cite('#44')).replace('#21', cite('#21'))}.")
for line in N["merged"]:
    w(f"- **Written twice:** {line}.")
w("")
w("### Copy")
w("")
for sid, text, why in N["copy-noted"]:
    w(f"- `{sid}`: “{text}” — {why}.")
by_state = collections.defaultdict(list)
for sid, text, where in N["copy-table"]:
    by_state[sid].append(text)
w(f"- **{len(N['copy-table'])} lines from DECISIONS' copy table** *(copy written during the build, awaiting ratification)* "
  "are now said-lines of their states, `provisional` (the agent door's, which you ratified, `ratified`). "
  "They are still listed in the table for you to ratify:")
for sid, texts in by_state.items():
    w(f"  - `{sid}`: " + " · ".join(f"“{t}”" for t in texts))
w("- Not a state's line, so left in the table only: " + "; ".join(x[1].split(" (")[0] for x in N["copy-table-skipped"]) + ".")
w("")

w("## Edges and rules")
w("")
w("**Moves that hold for a group are rules** (your pick (b)). The tests will expand each into its moves. "
  "Every rule, with the moves of the recorded run it covers:")
w("")
w("| Rule | Says | Moves | Cites |")
w("|---|---|---|---|")
for r in M["rules"]:
    w(f"| **{r['label']}** | {r['says']} | {covered.get('rule:' + r['id'], 0)} | {cites(r['cites'])} |")
w("")
w(f"**The other edges only the code makes** (beyond the ratified batch): ")
rest = [e for e in new_edges if (e["from"], e["to"]) not in set(overlay.RULED_EDGES)]
w("")
w("| From | To | On | Cites |")
w("|---|---|---|---|")
for e in rest:
    w(f"| `{e['from']}` | `{e['to']}` | {e['label']} | {cites(e['cites'])} |")
w("")
arm_only = [e for e in M["edges"] if e["source"] == ["core-arm"]]
w(f"**{len(arm_only)} edges the core's arms name that no drawing had**, each from `EXTRA_ARM_EDGES`: "
  + "; ".join(f"`{e['from']}` → `{e['to']}` ({cites(e['cites'])})" for e in arm_only) + ".")
w("")


def fam(s):
    out = {s}
    while S.get(s, {}).get("parent"):
        s = S[s]["parent"]
        out.add(s)
    return out


made = {(m["from"], m["to"]) for m in MOVES}
web = {"web-page", "terminal", "other"}
unmade = []
for e in M["edges"]:
    if e["on"] or "core-run" in e["source"]:
        continue
    a, b = S[e["from"]], S[e["to"]]
    if a["surface"] in web or b["surface"] in web:
        continue
    if any(e["from"] in fam(f) | {f} and e["to"] in fam(t) | {t} for f, t in made):
        continue
    unmade.append(e)
w(f"**{len(unmade)} drawn edges between the app's states that no test made verbatim.** Most are reached under "
  "another name (a face, a window's tab) or happen only across a relaunch; phase 2's tests decide each one. "
  "The pages' and the installer's edges (the Worker, the site, `install.sh`) aren't the core's, so they're kept as drawn.")
w("")
w("<details><summary>The list</summary>")
w("")
for e in unmade:
    w(f"- `{e['from']}` → `{e['to']}` — {e['label'] or e['trigger']}")
w("")
w("</details>")
w("")

w("## Loose ends")
w("")
w("- The deviations table skips #33–35 and #37: numbered, never written. Nothing in the JSON cites them.")
w("- Fixture transitions whose target was prose: those naming a state now go there; the derived returns "
  "(“(derived — re-probe)”, a window reopened after an update, the app quitting) are the rules' (`relaunch`, `offline`, …).")
w("- Each state's `board` (its screen on the canvas) is the probe's guess for now; phase 4 settles it.")
w("- The map's 13 notes are kept as `notes`, with their text and the states they're about.")
w("")
w("## How it was made")
w("")
w("1. `record-moves.patch` makes every shroom-core test log each step (where each surface stood before and after, "
  "the event, the arm and the edge it named); `reduce-moves.py` folds the log to `moves.json`.")
w("2. `assemble.py` merges the fixtures, the map and `meta.json` under `ids.py`'s one id per state, lays `overlay.py` "
  "over them (the code-only states, shipped copy under its rows, the copy table, the edges the build changed), "
  "adds the core's named edges, then holds every recorded move to the edges and `rules.py`; what nothing covers "
  "becomes a `provisional` edge.")
w("3. `report.py` writes this.")
(HERE / "REPORT.md").write_text("\n".join(out) + "\n")
print(f"REPORT.md: {len(out)} lines")
